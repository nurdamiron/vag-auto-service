function caseVignette(slug, model, pack, intent) {
  const h = hash(slug);
  const years = [2011, 2012, 2013, 2014, 2015, 2016, 2017, 2018, 2019];
  const km = [86, 112, 128, 142, 157, 168, 184, 203, 227];
  const places = [
    "после мойки на Саина",
    "после ямы на Абая",
    "на подъёме к Медеу",
    "в пробке на Аль-Фараби",
    "после трассы на Капшагай",
    "во дворе в Таугуле",
    "на спуске с Шымбулака",
    "после ночи на улице в январе",
  ];
  const year = years[h % years.length];
  const mileage = km[(h >> 3) % km.length];
  const place = places[(h >> 6) % places.length];
  const who = model ? `${model.brandName} ${model.name}` : pack.problem;
  if (intent === "buy") {
    return `Типичный заезд: ${who}, около ${year} года, на щитке ${mileage} тысяч. Продавец говорит «не бита, не крашена», ${place} это уже не проверить.`;
  }
  return `Недавний заезд: ${who}${model ? `, ${year} год, ${mileage} тыс. км` : ""}. Симптом всплыл ${place}.`;
}

