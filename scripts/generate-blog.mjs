function main() {
  uniqueCheck(ROWS);
  if (ROWS.length < 200) {
    throw new Error(`Need 200 articles, got ${ROWS.length}`);
  }
  const posts = ROWS.slice(0, 200).map((row, i) => writePost(row, i));
  if (posts.length !== 200) throw new Error(`Expected 200, got ${posts.length}`);

  mkdirSync(dirname(outJson), { recursive: true });
  writeFileSync(outJson, JSON.stringify(posts, null, 2), "utf8");

  mkdirSync(coverDir, { recursive: true });
  for (const post of posts) {
    writeFileSync(join(coverDir, `${post.slug}.svg`), coverSvg(post), "utf8");
  }

  const cats = {};
  for (const p of posts) cats[p.category] = (cats[p.category] ?? 0) + 1;
  console.log(`Wrote ${posts.length} posts -> ${outJson}`);
  console.log(`Wrote ${posts.length} covers -> ${coverDir}`);
  console.log("Categories:", cats);
}

main();
