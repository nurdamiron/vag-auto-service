function uniqueCheck(rows) {
  const slugs = new Set();
  const titles = new Set();
  const keywords = new Set();
  for (const row of rows) {
    const [slug, title, , , , keyword] = row;
    if (slugs.has(slug)) throw new Error(`Duplicate slug: ${slug}`);
    if (titles.has(title)) throw new Error(`Duplicate title: ${title}`);
    if (keywords.has(keyword)) throw new Error(`Duplicate keyword: ${keyword}`);
    slugs.add(slug);
    titles.add(title);
    keywords.add(keyword);
  }
}

function wrapText(text, max = 28) {
  const words = text.split(" ");
  const lines = [];
  let line = "";
  for (const w of words) {
    const next = line ? `${line} ${w}` : w;
    if (next.length > max && line) {
      lines.push(line);
      line = w;
    } else {
      line = next;
    }
  }
  if (line) lines.push(line);
  return lines.slice(0, 4);
}

