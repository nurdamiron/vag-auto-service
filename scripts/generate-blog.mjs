function escapeXml(s) {
  return s
    .replaceAll("&", "&amp;")
    .replaceAll("<", "&lt;")
    .replaceAll(">", "&gt;")
    .replaceAll('"', "&quot;");
}

function brandName(key) {
  return key ? BRANDS[key]?.name ?? null : null;
}

function modelBlock(modelKey) {
  if (!modelKey || !MODELS[modelKey]) return null;
  const m = MODELS[modelKey];
  const b = BRANDS[m.brand];
  return { ...m, brandName: b.name, group: b.group };
}

